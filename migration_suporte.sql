-- =====================================================================
-- SUPORTE E FEEDBACK (zzz208)
-- A equipe relata problema (bug), sugestão, dúvida ou elogio direto do
-- sistema, com print e informações da tela. Admin/coordenador respondem
-- e mudam o andamento; a pessoa recebe aviso no sino. Só acrescenta.
-- Tabelas: suporte_chamados, suporte_mensagens. Pasta privada: suporte.
-- Escrita só pelas funções abaixo (a leitura é de quem abriu + admin/coord.).
-- =====================================================================
create table if not exists public.suporte_chamados (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity,
  tipo text not null check (tipo in ('bug', 'sugestao', 'duvida', 'elogio')),
  titulo text not null check (char_length(btrim(titulo)) between 3 and 140),
  descricao text not null default '' check (char_length(descricao) <= 4000),
  urgente boolean not null default false,
  status text not null default 'novo' check (status in ('novo', 'em_analise', 'em_andamento', 'resolvido', 'nao_vamos_fazer')),
  prioridade text not null default 'normal' check (prioridade in ('baixa', 'normal', 'alta')),
  criado_por uuid not null,
  criado_por_nome text,
  contexto jsonb not null default '{}'::jsonb,
  anexos text[] not null default '{}',
  resolvido_em timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.suporte_mensagens (
  id uuid primary key default gen_random_uuid(),
  chamado_id uuid not null,
  autor_id uuid not null,
  autor_nome text,
  texto text not null check (char_length(btrim(texto)) between 1 and 4000),
  interno boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists suporte_mensagens_chamado_idx on public.suporte_mensagens (chamado_id, created_at);
create index if not exists suporte_chamados_status_idx on public.suporte_chamados (status, created_at desc);
alter table public.suporte_chamados enable row level security;
alter table public.suporte_mensagens enable row level security;
create policy suporte_chamados_ler on public.suporte_chamados for select using (criado_por = (select auth.uid()) or public.sou_equipe());
create policy suporte_mensagens_ler on public.suporte_mensagens for select using (
  exists (select 1 from public.suporte_chamados c where c.id = chamado_id and (c.criado_por = (select auth.uid()) or public.sou_equipe()))
  and (not interno or public.sou_equipe()));
grant select on public.suporte_chamados, public.suporte_mensagens to authenticated;
revoke all on public.suporte_chamados from anon;
revoke all on public.suporte_mensagens from anon;

