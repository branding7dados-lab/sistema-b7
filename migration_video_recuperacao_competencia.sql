-- =========================================================================
-- RECUPERAÇÃO DE COMPETÊNCIA — lote 'PLANILHA DE GRAVAÇÕES (1).xlsx'
-- =========================================================================
-- Por que este script existe: as 367 demandas já confirmadas a partir
-- desse lote nunca tiveram a coluna "Mês" da planilha salva em
-- dados_originais->>'ano'/'mes' (esse campo só passou a ser salvo a
-- partir do build 2026-09-14-e). Sem isso guardado,
-- video_backfill_competencia() não tinha de onde recuperar — todas as
-- 367 demandas ficaram com a competência padrão do dia em que a
-- importação foi confirmada (setembro/2026), em vez do mês real de
-- cada trabalho.
--
-- Este script reconstrói o valor certo cruzando cada linha já
-- confirmada (por linha_numero) com o MESMO arquivo original
-- ("PLANILHA DE GRAVAÇÕES (1).xlsx", as mesmas 731 linhas, mesma
-- ordem) que você usou na importação real — confirmado por você e
-- verificado aqui batendo 16 linhas de amostra (cliente + código +
-- título, espalhadas do início ao fim do arquivo) uma a uma antes de
-- gerar este script. 730 das 731 linhas do arquivo têm mês/ano
-- legítimos; a única sem mês/ano é uma linha em branco na planilha
-- (sem cliente, sem título) que nunca virou demanda.
--
-- O que o script faz, nesta ordem:
--   1. Cria uma tabela temporária com (linha_numero, ano_fonte, mes_fonte)
--      reconstruídos diretamente do arquivo original.
--   2. Faz merge desses valores dentro de dados_originais das linhas de
--      importação já confirmadas (só ADICIONA as chaves 'ano'/'mes' que
--      faltavam — não toca em mais nada do que já estava salvo).
--   3. Roda video_backfill_competencia(), a MESMA função já entregue no
--      build 2026-09-14-e — ela lê o dados_originais agora completo e
--      corrige demandas_edicao.competencia_ano/mes só onde diverge,
--      e devolve uma linha por demanda alterada (para você conferir
--      antes/depois de cada uma).
--   4. Apaga a tabela temporária.
--
-- Idempotente: pode rodar de novo sem dano (a segunda vez não muda
-- nada, porque dados_originais já vai ter as chaves e
-- video_backfill_competencia() só altera o que diverge).
-- =========================================================================

